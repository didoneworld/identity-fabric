#!/usr/bin/env bash
# One-time setup of a fresh OVHcloud VPS (Ubuntu 24.04 / Debian 12) for Identity Fabric.
#
# Run as root (or with sudo) on the VPS:
#   curl -fsSL https://raw.githubusercontent.com/didoneworld/identity-fabric/main/deploy/ovh/bootstrap.sh -o bootstrap.sh
#   sudo DOMAIN=identity.example.com ACME_EMAIL=ops@example.com \
#        DEPLOY_PUBKEY="ssh-ed25519 AAAA... github-actions" bash bootstrap.sh
#
# Optional: HARDEN_SSH=1 disables SSH password and root login. Only set it after
# confirming you can log in with a key, or you will lock yourself out.
#
# Safe to re-run: existing users, keys and .env are left alone.
set -euo pipefail

DOMAIN="${DOMAIN:?DOMAIN is required (DNS A/AAAA record must point at this VPS)}"
ACME_EMAIL="${ACME_EMAIL:?ACME_EMAIL is required (TLS certificate notices)}"
DEPLOY_PUBKEY="${DEPLOY_PUBKEY:?DEPLOY_PUBKEY is required (public half of the GitHub Actions deploy key)}"
DEPLOY_USER="${DEPLOY_USER:-deploy}"
APP_DIR="${APP_DIR:-/opt/identity-fabric}"
HARDEN_SSH="${HARDEN_SSH:-0}"

[[ $EUID -eq 0 ]] || { echo "Run as root (sudo)." >&2; exit 1; }
log() { printf '\n==> %s\n' "$*"; }

log "Installing base packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -yq ca-certificates curl openssl ufw fail2ban unattended-upgrades
dpkg-reconfigure -f noninteractive unattended-upgrades

if ! command -v docker >/dev/null; then
  log "Installing Docker Engine + Compose plugin (get.docker.com)"
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker
docker compose version

log "Configuring deploy user '$DEPLOY_USER'"
id "$DEPLOY_USER" >/dev/null 2>&1 || useradd --create-home --shell /bin/bash "$DEPLOY_USER"
usermod -aG docker "$DEPLOY_USER"
install -d -m 700 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "/home/$DEPLOY_USER/.ssh"
AUTH_KEYS="/home/$DEPLOY_USER/.ssh/authorized_keys"
touch "$AUTH_KEYS"
grep -qxF "$DEPLOY_PUBKEY" "$AUTH_KEYS" || echo "$DEPLOY_PUBKEY" >> "$AUTH_KEYS"
chown "$DEPLOY_USER:$DEPLOY_USER" "$AUTH_KEYS"; chmod 600 "$AUTH_KEYS"

log "Firewall: allow SSH, HTTP, HTTPS (incl. HTTP/3)"
ufw default deny incoming
ufw default allow outgoing
ufw allow OpenSSH
ufw allow 80/tcp
ufw allow 443/tcp
ufw allow 443/udp
ufw --force enable
# Note: Docker-published ports bypass ufw. Compose only publishes 80/443;
# SurrealDB and the API stay on the internal Docker network.

if [[ "$HARDEN_SSH" == "1" ]]; then
  log "Hardening SSH (key-only, no root login)"
  cat > /etc/ssh/sshd_config.d/99-identity-fabric.conf <<'EOF'
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
EOF
  if ! sshd -t; then
    rm -f /etc/ssh/sshd_config.d/99-identity-fabric.conf
    echo "sshd config test failed; hardening reverted, SSH left unchanged." >&2
    exit 1
  fi
  systemctl reload ssh 2>/dev/null || systemctl reload sshd
fi

log "Preparing $APP_DIR"
install -d -m 750 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$APP_DIR" "$APP_DIR/backups"
ENV_FILE="$APP_DIR/.env"
if [[ ! -f "$ENV_FILE" ]]; then
  # Generate outside the heredoc: a failed $(...) inside it would silently leave a blank secret.
  surreal_pass="$(openssl rand -hex 24)"
  enc_key="$(openssl rand -hex 32)"
  hmac_key="$(openssl rand -hex 32)"
  agent_secret="$(openssl rand -hex 32)"
  for v in "$surreal_pass" "$enc_key" "$hmac_key" "$agent_secret"; do
    [[ "$v" =~ ^[0-9a-f]{48,64}$ ]] || { echo "secret generation failed" >&2; exit 1; }
  done
  cat > "$ENV_FILE" <<EOF
# Generated by bootstrap.sh on $(date -u +%FT%TZ). Back this file up somewhere safe:
# losing IDENTITY_FABRIC_ENC_KEY makes stored personal data unrecoverable.
DOMAIN=$DOMAIN
ACME_EMAIL=$ACME_EMAIL
SURREAL_USER=root
SURREAL_PASS=$surreal_pass
SURREAL_NS=autonomyx
SURREAL_DB=identity_fabric
IDENTITY_FABRIC_ENC_KEY=$enc_key
IDENTITY_FABRIC_HMAC_KEY=$hmac_key
AUTONOMYX_AGENT_SECRET=$agent_secret
LOGTO_ENDPOINT=
LOGTO_AUDIENCE=
TENANT_CLAIM=tenant_id
DEFAULT_TENANT_ID=
MAX_EDGE_DEPTH=3
ENRICH_TTL_HOURS=24
IMAGE=ghcr.io/didoneworld/identity-fabric
IMAGE_TAG=latest
EOF
  chown "$DEPLOY_USER:$DEPLOY_USER" "$ENV_FILE"; chmod 600 "$ENV_FILE"
  echo "Created $ENV_FILE with fresh secrets. Add provider connector settings as needed (see .env.example)."
else
  echo "$ENV_FILE exists; left unchanged."
fi

log "Daily SurrealDB backup at 02:17 UTC (keeps 14 days)"
cat > /etc/cron.d/identity-fabric-backup <<EOF
17 2 * * * $DEPLOY_USER cd $APP_DIR && ./scripts/backup.sh >> $APP_DIR/backups/backup.log 2>&1
EOF

log "Done"
cat <<EOF
Next steps:
  1. Point DNS for $DOMAIN at this server's IPv4 (A) and IPv6 (AAAA).
  2. In GitHub (Settings -> Environments -> production) set:
       OVH_HOST=<this server's IP or hostname>   OVH_USER=$DEPLOY_USER
       OVH_SSH_KEY=<private half of DEPLOY_PUBKEY>
       OVH_KNOWN_HOSTS=<output of: ssh-keyscan -t ed25519 <host>>
       (variable) DOMAIN=$DOMAIN
  3. Run the "Deploy to OVH" workflow (or push to main).
  4. Copy $ENV_FILE to your password manager.
EOF
